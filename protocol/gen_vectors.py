"""Generate cross-language conformance vectors for SilkNet v1.

Outputs:
  protocol/test-vectors.json                         (Go ingest tests, Python tests)
  firmware/spider-node/test/golden/silknet_vectors.h (C++ firmware unit tests)

Reference implementation: pyca/cryptography (OpenSSL) AES-ECB / AES-CCM.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from silknet import TYPES, Detection, derive_node_key, encode  # noqa: E402

ROOT = HERE.parent


def aes_ecb(key: bytes, block: bytes) -> bytes:
    enc = Cipher(algorithms.AES(key), modes.ECB()).encryptor()  # noqa: S305 - single-block KAT only
    return enc.update(block) + enc.finalize()


def main() -> None:
    # FIPS-197 Appendix C.1 known-answer test.
    fips_key = bytes(range(16))
    fips_pt = bytes.fromhex("00112233445566778899aabbccddeeff")
    fips_ct = aes_ecb(fips_key, fips_pt)
    assert fips_ct.hex() == "69c4e0d86a7b0430d8cdb78070b4c55a", "FIPS-197 KAT mismatch"

    # RFC 3610 Packet Vector #1 (M = 8, L = 2).
    from cryptography.hazmat.primitives.ciphers.aead import AESCCM

    rfc_key = bytes.fromhex("c0c1c2c3c4c5c6c7c8c9cacbcccdcecf")
    rfc_nonce = bytes.fromhex("00000003020100a0a1a2a3a4a5")
    rfc_aad = bytes(range(8))
    rfc_pt = bytes(range(8, 31))
    rfc_out = AESCCM(rfc_key, tag_length=8).encrypt(rfc_nonce, rfc_pt, rfc_aad)
    assert rfc_out.hex() == "588c979a61c663d2f066d0c2c0f989806d5f6b61dac38417e8d12cfdf926e0", "RFC 3610 #1 mismatch"

    site_key = bytes.fromhex("2b7e151628aed2a6abf7158809cf4f3c")
    frames = []
    cases = [
        ("detection-footsteps", TYPES["DETECTION"], 0x00, 7, 5, 1001, Detection(1795035900, 1, 0.94, 22.4, 1430, 87, 0)),
        ("benign-animal-relayed", TYPES["BENIGN"], 0b00000110, 7, 21, 77, Detection(1795035904, 5, 0.12, 15.0, 820, 91, 0)),
        ("tamper-last-gasp", TYPES["TAMPER"], 0x01, 7, 21, 78, Detection(1795035910, 0, 1.0, 0, 0, 90, 0b001)),
        ("heartbeat", TYPES["HEARTBEAT"], 0x00, 2, 1, 4_000_000_000, Detection(1795035600, 0, 0, 0, 0, 64, 0b010)),
    ]
    for name, ftype, flags, site, node, counter, det in cases:
        k = derive_node_key(site_key, site, node)
        payload = det.pack()
        frame = encode(ftype, flags, site, node, counter, payload, k)
        frames.append({
            "name": name, "type": ftype, "flags": flags, "site_id": site, "node_id": node, "counter": counter,
            "node_key": k.hex(), "payload": payload.hex(), "frame": frame.hex(),
            "decoded": {"window_start": det.window_start, "class_id": det.class_id,
                        "p_threat_u8": payload[5], "snr_db": det.snr_db, "arrival_ms": det.arrival_ms,
                        "battery_pct": det.battery_pct, "status": det.status},
        })

    vectors = {
        "fips197": {"key": fips_key.hex(), "plaintext": fips_pt.hex(), "ciphertext": fips_ct.hex()},
        "rfc3610_1": {"key": rfc_key.hex(), "nonce": rfc_nonce.hex(), "aad": rfc_aad.hex(), "plaintext": rfc_pt.hex(),
                      "output": rfc_out.hex(), "tag_len": 8},
        "site_key": site_key.hex(),
        "frames": frames,
    }
    (HERE / "test-vectors.json").write_text(json.dumps(vectors, indent=2), encoding="utf-8")

    def carr(h: str) -> str:
        b = bytes.fromhex(h)
        return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}"

    lines = [
        "// AUTO-GENERATED by protocol/gen_vectors.py - DO NOT EDIT.",
        "#pragma once",
        "#include <cstdint>",
        "#include <cstddef>",
        "",
        "namespace silknet::vectors {",
        f"constexpr uint8_t kFipsKey[16] = {carr(fips_key.hex())};",
        f"constexpr uint8_t kFipsPlain[16] = {carr(fips_pt.hex())};",
        f"constexpr uint8_t kFipsCipher[16] = {carr(fips_ct.hex())};",
        f"constexpr uint8_t kRfcKey[16] = {carr(rfc_key.hex())};",
        f"constexpr uint8_t kRfcNonce[13] = {carr(rfc_nonce.hex())};",
        f"constexpr uint8_t kRfcAad[8] = {carr(rfc_aad.hex())};",
        f"constexpr uint8_t kRfcPlain[23] = {carr(rfc_pt.hex())};",
        f"constexpr uint8_t kRfcOut[31] = {carr(rfc_out.hex())};",
        f"constexpr uint8_t kSiteKey[16] = {carr(site_key.hex())};",
        "",
        "struct Frame {",
        "    const char* name; uint8_t type; uint8_t flags; uint16_t site; uint16_t node; uint32_t counter;",
        "    uint8_t key[16]; uint8_t payload[14]; uint8_t frame[32];",
        "};",
        f"constexpr size_t kNumFrames = {len(frames)};",
        "constexpr Frame kFrames[kNumFrames] = {",
    ]
    for f in frames:
        lines.append(f'    {{"{f["name"]}", {f["type"]}, {f["flags"]}, {f["site_id"]}, {f["node_id"]}, {f["counter"]}u, '
                     f'{carr(f["node_key"])}, {carr(f["payload"])}, {carr(f["frame"])}}},')
    lines += ["};", "", "}  // namespace silknet::vectors", ""]
    out_h = ROOT / "firmware" / "spider-node" / "test" / "golden" / "silknet_vectors.h"
    out_h.parent.mkdir(parents=True, exist_ok=True)
    out_h.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(frames)} frames; FIPS-197 and RFC 3610 reference checks passed")


if __name__ == "__main__":
    main()
