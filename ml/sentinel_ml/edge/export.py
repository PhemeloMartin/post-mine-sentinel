"""Export the trained edge MLP to C++ headers and golden test vectors.

Outputs
-------
firmware/spider-node/lib/sentinel_core/include/sentinel/model_weights.h
    constexpr float tables consumed by ``classifier.cpp`` (flash-resident on ESP32).
firmware/spider-node/test/golden/golden_vectors.h
    raw int16 windows + expected features + expected probabilities, one per class.
    The firmware unit tests assert C++ ≡ Python within tolerance (feature parity).
ml/artifacts/golden_vectors.json
    same data for other consumers (docs, the web simulator, regression tests).
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from sklearn.neural_network import MLPClassifier
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

from ..features import FEATURE_NAMES, extract_features
from ..signals import CLASSES, THREAT_CLASSES

HEADER_BANNER = (
    "// AUTO-GENERATED by ml/sentinel_ml/edge/export.py - DO NOT EDIT BY HAND.\n"
    "// Regenerate with:  python ml/scripts/train_edge.py\n"
)


def _fmt(v: float) -> str:
    return f"{float(v):.9g}f"


def _arr1(values) -> str:
    return "{" + ", ".join(_fmt(v) for v in values) + "}"


def _arr2(matrix) -> str:
    rows = ",\n    ".join(_arr1(r) for r in matrix)
    return "{\n    " + rows + "\n}"


def write_model_header(model: Pipeline, threshold: float, path: Path) -> None:
    scaler: StandardScaler = model.named_steps["scale"]
    clf: MLPClassifier = model.named_steps["clf"]
    w1, w2, w3 = clf.coefs_
    b1, b2, b3 = clf.intercepts_
    n_in, h1 = w1.shape
    h2, n_out = w2.shape[1], w3.shape[1]
    names = ", ".join(f'"{c}"' for c in CLASSES)
    threat = ", ".join("true" if i in THREAT_CLASSES else "false" for i in range(len(CLASSES)))
    feat_names = ", ".join(f'"{f}"' for f in FEATURE_NAMES)
    text = f"""{HEADER_BANNER}#pragma once

namespace sentinel::model {{

constexpr int kNumFeatures = {n_in};
constexpr int kHidden1 = {h1};
constexpr int kHidden2 = {h2};
constexpr int kNumClasses = {n_out};

/// P(threat) alarm threshold chosen for a <= 2 % benign false-alarm rate on validation data.
constexpr float kAlarmThreshold = {_fmt(threshold)};

constexpr const char* kFeatureNames[kNumFeatures] = {{{feat_names}}};
constexpr const char* kClassNames[kNumClasses] = {{{names}}};
constexpr bool kIsThreat[kNumClasses] = {{{threat}}};

/// z = (x - mean) / scale  (sklearn StandardScaler)
constexpr float kFeatureMean[kNumFeatures] = {_arr1(scaler.mean_)};
constexpr float kFeatureScale[kNumFeatures] = {_arr1(scaler.scale_)};

/// Dense layers, row-major [inputs][outputs] exactly as sklearn's coefs_.
constexpr float kW1[kNumFeatures][kHidden1] = {_arr2(w1)};
constexpr float kB1[kHidden1] = {_arr1(b1)};
constexpr float kW2[kHidden1][kHidden2] = {_arr2(w2)};
constexpr float kB2[kHidden2] = {_arr1(b2)};
constexpr float kW3[kHidden2][kNumClasses] = {_arr2(w3)};
constexpr float kB3[kNumClasses] = {_arr1(b3)};

}}  // namespace sentinel::model
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def golden_vectors(model: Pipeline, raw: np.ndarray, y: np.ndarray) -> list[dict]:
    out = []
    for c in range(len(CLASSES)):
        idx = int(np.flatnonzero(y == c)[0])
        window = raw[idx]
        feats = extract_features(window)
        proba = model.predict_proba(feats[None, :])[0]
        out.append({
            "label": c,
            "class": CLASSES[c],
            "raw": window.astype(int).tolist(),
            "features": [float(v) for v in feats],
            "proba": [float(v) for v in proba],
        })
    return out


def write_golden_header(vectors: list[dict], path: Path) -> None:
    raws = ",\n    ".join("{" + ", ".join(str(v) for v in g["raw"]) + "}" for g in vectors)
    feats = ",\n    ".join(_arr1(g["features"]) for g in vectors)
    probas = ",\n    ".join(_arr1(g["proba"]) for g in vectors)
    labels = ", ".join(str(g["label"]) for g in vectors)
    text = f"""{HEADER_BANNER}#pragma once
#include <cstdint>

namespace sentinel::golden {{

constexpr int kNumVectors = {len(vectors)};
constexpr int kWindow = {len(vectors[0]['raw'])};
constexpr int kNumFeatures = {len(vectors[0]['features'])};
constexpr int kNumClasses = {len(vectors[0]['proba'])};

constexpr int kLabel[kNumVectors] = {{{labels}}};
constexpr int16_t kRaw[kNumVectors][kWindow] = {{
    {raws}
}};
constexpr float kFeatures[kNumVectors][kNumFeatures] = {{
    {feats}
}};
constexpr float kProba[kNumVectors][kNumClasses] = {{
    {probas}
}};

}}  // namespace sentinel::golden
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def export_all(model: Pipeline, threshold: float, raw: np.ndarray, y: np.ndarray,
               repo_root: Path, artifacts: Path) -> None:
    fw = repo_root / "firmware" / "spider-node"
    write_model_header(model, threshold, fw / "lib" / "sentinel_core" / "include" / "sentinel" / "model_weights.h")
    vectors = golden_vectors(model, raw, y)
    write_golden_header(vectors, fw / "test" / "golden" / "golden_vectors.h")
    (artifacts / "golden_vectors.json").write_text(json.dumps(vectors), encoding="utf-8")
