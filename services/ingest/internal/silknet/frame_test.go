type vectorFile struct {
	FIPS197 struct {
		Key, Plaintext, Ciphertext string
	} `json:"fips197"`
	RFC3610 struct {
		Key, Nonce, AAD, Plaintext, Output string
		TagLen                             int `json:"tag_len"`
	} `json:"rfc3610_1"`
	SiteKey string `json:"site_key"`
	Frames  []struct {
		Name    string `json:"name"`
		Type    byte   `json:"type"`
		Flags   byte   `json:"flags"`
		SiteID  uint16 `json:"site_id"`
		NodeID  uint16 `json:"node_id"`
		Counter uint32 `json:"counter"`
		NodeKey string `json:"node_key"`
		Payload string `json:"payload"`
		Frame   string `json:"frame"`
		Decoded struct {
			WindowStart uint32 `json:"window_start"`
			ClassID     byte   `json:"class_id"`
			PThreatU8   byte   `json:"p_threat_u8"`
			ArrivalMs   uint16 `json:"arrival_ms"`
			BatteryPct  byte   `json:"battery_pct"`
			Status      byte   `json:"status"`
		} `json:"decoded"`
	} `json:"frames"`
}

func mustHex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatalf("bad hex %q: %v", s, err)
	}
	return b
}

// Vectors are generated by protocol/gen_vectors.py with the pyca/cryptography reference.
func loadVectors(t *testing.T) vectorFile {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("..", "..", "..", "..", "protocol", "test-vectors.json"))
	if err != nil {
		t.Fatalf("read vectors: %v", err)
	}
	var v vectorFile
	if err := json.Unmarshal(raw, &v); err != nil {
		t.Fatalf("parse vectors: %v", err)
	}
	return v
}

func TestAESKnownAnswer(t *testing.T) {
	v := loadVectors(t)
	block, err := aes.NewCipher(mustHex(t, v.FIPS197.Key))
	if err != nil {
		t.Fatal(err)
	}
	out := make([]byte, 16)
	block.Encrypt(out, mustHex(t, v.FIPS197.Plaintext))
	if !bytes.Equal(out, mustHex(t, v.FIPS197.Ciphertext)) {
		t.Fatalf("FIPS-197: got %x", out)
	}
}

func TestCCMMatchesRFC3610(t *testing.T) {
	v := loadVectors(t)
	block, _ := aes.NewCipher(mustHex(t, v.RFC3610.Key))
	c, err := newCCM(block, v.RFC3610.TagLen)
	if err != nil {
		t.Fatal(err)
	}
	sealed, err := c.Seal(mustHex(t, v.RFC3610.Nonce), mustHex(t, v.RFC3610.Plaintext), mustHex(t, v.RFC3610.AAD))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(sealed, mustHex(t, v.RFC3610.Output)) {
		t.Fatalf("RFC 3610 #1:\n got %x\nwant %s", sealed, v.RFC3610.Output)
	}
	pt, err := c.Open(mustHex(t, v.RFC3610.Nonce), sealed, mustHex(t, v.RFC3610.AAD))
	if err != nil || !bytes.Equal(pt, mustHex(t, v.RFC3610.Plaintext)) {
		t.Fatalf("round trip failed: %v", err)
	}
}

func TestFramesDecodeAndReencodeExactly(t *testing.T) {
	v := loadVectors(t)
	siteKey := mustHex(t, v.SiteKey)
	keys := func(uint16) ([]byte, bool) { return siteKey, true }
	for _, f := range v.Frames {
		t.Run(f.Name, func(t *testing.T) {
			if got := DeriveNodeKey(siteKey, f.SiteID, f.NodeID); !bytes.Equal(got, mustHex(t, f.NodeKey)) {
				t.Fatalf("KDF: got %x want %s", got, f.NodeKey)
			}
			frame := mustHex(t, f.Frame)
			h, pt, err := Open(frame, keys)
			if err != nil {
				t.Fatalf("open: %v", err)
			}
			if h.Type != f.Type || h.SiteID != f.SiteID || h.NodeID != f.NodeID || h.Counter != f.Counter || h.Flags != f.Flags {
				t.Fatalf("header mismatch: %+v", h)
			}
			d, err := ParseDetection(pt)
			if err != nil {
				t.Fatalf("payload: %v", err)
			}
			want := f.Decoded
			if d.WindowStart != want.WindowStart || d.ClassID != want.ClassID || d.PThreatU8 != want.PThreatU8 ||
				d.ArrivalMs != want.ArrivalMs || d.BatteryPct != want.BatteryPct || d.Status != want.Status {
				t.Fatalf("decoded %+v want %+v", d, want)
			}
			again, err := Seal(h, pt, mustHex(t, f.NodeKey))
			if err != nil || !bytes.Equal(again, frame) {
				t.Fatalf("re-encode mismatch: %x", again)
			}
		})
	}
}

func TestTamperedFramesFailClosed(t *testing.T) {
	v := loadVectors(t)
	siteKey := mustHex(t, v.SiteKey)
	keys := func(uint16) ([]byte, bool) { return siteKey, true }
	frame := mustHex(t, v.Frames[0].Frame)
	for _, idx := range []int{0, 2, 7, HeaderLen + 3, len(frame) - 1} {
		bad := append([]byte(nil), frame...)
		bad[idx] ^= 0x01
		if _, pt, err := Open(bad, keys); err == nil || pt != nil {
			t.Fatalf("flipping byte %d was not detected", idx)
		}
	}
	// The flags byte is mutable (hop count) and must NOT break authentication.
	relayed := append([]byte(nil), frame...)
	relayed[1] = 0b00001010
	if _, _, err := Open(relayed, keys); err != nil {
		t.Fatalf("hop-count change broke auth: %v", err)
	}
}

func TestRejectsUnknownSiteAndShortFrames(t *testing.T) {
	none := func(uint16) ([]byte, bool) { return nil, false }
	if _, _, err := Open(make([]byte, 5), none); err != ErrShort {
		t.Fatalf("want ErrShort, got %v", err)
	}
	v := loadVectors(t)
	if _, _, err := Open(mustHex(t, v.Frames[0].Frame), none); err != ErrUnknownSite {
		t.Fatalf("want ErrUnknownSite, got %v", err)
	}
}
